-- ==============================================================================
-- SECURITY HELPER FUNCTIONS (Non-recursive SECURITY DEFINER)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.get_my_company_id()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
DECLARE
    cid INTEGER;
BEGIN
    SELECT company_id INTO cid
    FROM public.profiles
    WHERE id = auth.uid();

    IF cid IS NULL THEN
        SELECT company_id INTO cid
        FROM public.employees
        WHERE user_id = auth.uid();
    END IF;

    RETURN cid;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_my_employee_id()
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
DECLARE
    eid UUID;
BEGIN
    SELECT id INTO eid
    FROM public.employees
    WHERE user_id = auth.uid();

    RETURN eid;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
DECLARE
    rname TEXT;
BEGIN
    SELECT r.name INTO rname
    FROM public.employees e
    JOIN public.roles r ON r.id = e.role_id
    WHERE e.user_id = auth.uid();

    RETURN rname;
END;
$$;

CREATE OR REPLACE FUNCTION public.is_super_admin()
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
BEGIN
    RETURN (public.get_my_role() = 'super_admin');
END;
$$;

