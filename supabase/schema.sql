-- 21. WORK LOCATIONS
CREATE TABLE IF NOT EXISTS public.work_locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    location_type TEXT NOT NULL DEFAULT 'Office'
        CHECK (location_type IN (
            'Office', 'Market', 'Store', 'Supermarket', 'Client Location',
            'Warehouse', 'Branch', 'Distributor', 'Event Location', 'Other'
        )),
    address TEXT,
    state TEXT NOT NULL DEFAULT 'Lagos',
    lga TEXT,
    city TEXT,
    latitude NUMERIC(10,7) NOT NULL,
    longitude NUMERIC(10,7) NOT NULL,
    geofence_radius_meters INTEGER NOT NULL DEFAULT 150
        CHECK (geofence_radius_meters >= 20 AND geofence_radius_meters <= 10000),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT work_locations_company_name_unique UNIQUE(company_id, name)
);

