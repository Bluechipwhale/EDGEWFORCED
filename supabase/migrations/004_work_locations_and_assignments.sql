CREATE POLICY work_locations_tenant_isolation ON public.work_locations
    FOR ALL
    USING (company_id = (
        SELECT company_id FROM public.profiles WHERE id = auth.uid()
    ))
    WITH CHECK (company_id = (
        SELECT company_id FROM public.profiles WHERE id = auth.uid()
